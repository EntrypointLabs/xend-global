/*
 * Writes src/jupiter-swap-layouts.ts from the interface description Jupiter
 * publishes on chain.
 *
 *   RPC_URL=<mainnet rpc> node scripts/generate-jupiter-layouts.mjs
 *
 * Run it again when Jupiter adds a venue. A venue missing from the table is
 * refused rather than guessed at, so being behind costs routes, not safety.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { inflateSync } from "node:zlib";

import { Connection, PublicKey } from "@solana/web3.js";

const here = dirname(fileURLToPath(import.meta.url));
const RPC = process.env.RPC_URL;
if (!RPC) throw new Error("set RPC_URL to a mainnet RPC");

const JUPITER = new PublicKey("JUP6LkbZbjS1jKKwapdHNy74zcZ3tLUZoi5QNyVTaV4");
// Anchor keeps a program's interface in an account at a fixed address: an
// 8-byte tag, the authority, a length, then the zlib-compressed JSON.
const IDL_HEADER = 44;

const [base] = PublicKey.findProgramAddressSync([], JUPITER);
const address = await PublicKey.createWithSeed(base, "anchor:idl", JUPITER);
const account = await new Connection(RPC, "confirmed").getAccountInfo(address);
if (!account) throw new Error("Jupiter's interface account was not found");
const length = account.data.readUInt32LE(IDL_HEADER - 4);
const idl = JSON.parse(
  inflateSync(account.data.subarray(IDL_HEADER, IDL_HEADER + length)),
);

const types = new Map(idl.types.map((type) => [type.name, type.type]));
const WIDTHS = { bool: 1, u8: 1, i8: 1, u16: 2, i16: 2, u32: 4, i32: 4 };
Object.assign(WIDTHS, { u64: 8, i64: 8, u128: 16, i128: 16, pubkey: 32 });

function layoutOf(type) {
  if (typeof type === "string") {
    if (type === "bytes") return [["v", 1]];
    if (!(type in WIDTHS)) throw new Error(`unknown type ${type}`);
    return [WIDTHS[type]];
  }
  if (type.option) return [["o", ...layoutOf(type.option)]];
  if (type.vec) return [["v", ...layoutOf(type.vec)]];
  if (type.array) {
    const [element, count] = type.array;
    const one = merge(layoutOf(element));
    if (one.length !== 1 || typeof one[0] !== "number") {
      throw new Error("array of a variable-width type");
    }
    return [one[0] * count];
  }
  if (type.defined) return layoutOfDefined(type.defined.name);
  throw new Error(`unknown type ${JSON.stringify(type)}`);
}

function layoutOfDefined(name) {
  const type = types.get(name);
  if (!type) throw new Error(`undefined type ${name}`);
  if (type.kind === "struct") return fields(type.fields);
  const variants = type.variants.map((variant) =>
    merge(fields(variant.fields)),
  );
  // An enum whose variants carry nothing is its one-byte tag.
  if (variants.every((variant) => variant.length === 0)) return [1];
  return [["e", ...variants]];
}

function fields(list = []) {
  return list.flatMap((field) => layoutOf(field.type ?? field));
}

/** Neighbouring fixed widths become one. */
function merge(layout) {
  const merged = [];
  for (const part of layout) {
    const last = merged.length - 1;
    if (typeof part === "number" && typeof merged[last] === "number") {
      merged[last] += part;
    } else if (part !== 0) {
      merged.push(Array.isArray(part) ? [part[0], ...mergeTail(part)] : part);
    }
  }
  return merged;
}

function mergeTail([kind, ...rest]) {
  return kind === "e" ? rest.map(merge) : merge(rest);
}

const swap = types.get("Swap");
const rows = swap.variants.map(
  (variant) =>
    `  ${JSON.stringify(merge(fields(variant.fields)))}, // ${variant.name}`,
);

writeFileSync(
  join(here, "..", "src", "jupiter-swap-layouts.ts"),
  `// Generated by scripts/generate-jupiter-layouts.mjs. Do not edit by hand.

/**
 * How many bytes one piece of a venue's arguments takes: a fixed width, an
 * optional value ("o"), a length-prefixed list ("v"), or a tagged choice
 * between layouts ("e").
 */
export type Layout = readonly LayoutPart[];
export type LayoutPart =
  | number
  | readonly ["o" | "v", ...LayoutPart[]]
  | readonly ["e", ...Layout[]];

/**
 * The arguments each venue takes in a Jupiter route plan, by the venue's
 * position in Jupiter's own list.
 */
export const JUPITER_SWAP_LAYOUTS: readonly Layout[] = [
${rows.join("\n")}
];
`,
);
console.log(`wrote ${rows.length} venue layouts`);
